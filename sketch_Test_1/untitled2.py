# --- Convert .tflite to a C header, pure Python (no xxd needed) ---
input_path  = "/content/drive/MyDrive/bottlecap_model.tflite"
output_path = "/content/drive/MyDrive/bottlecap_model.h"

with open(input_path, "rb") as f:
    data = f.read()

# Build a C-style array with 12 bytes per line for readability
lines = []
for i in range(0, len(data), 12):
    chunk = data[i:i+12]
    lines.append("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")

array_body = "\n".join(lines)

header = f"""// Auto-generated from bottlecap_model.tflite
// Size: {len(data)} bytes ({len(data)/1024:.2f} KB)
#ifndef BOTTLECAP_MODEL_H
#define BOTTLECAP_MODEL_H

const unsigned int bottlecap_model_tflite_len = {len(data)};
const unsigned char bottlecap_model_tflite[] = {{
{array_body}
}};

#endif  // BOTTLECAP_MODEL_H
"""

with open(output_path, "w") as f:
    f.write(header)

